  function getSavedLang() {
    try { return localStorage.getItem("gepgeo_lang"); } catch (e) { return null; }
  }
  function saveLang(lang) {
    try { localStorage.setItem("gepgeo_lang", lang); } catch (e) {}
  }

  function applyLanguage(lang) {
    var dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key].replace(/<[^>]+>/g, ""));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key].replace(/<[^>]+>/g, ""));
    });

    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.classList.toggle("is-active", btn.dataset.lang === lang);
    });

    window.__gepgeoLang = lang;
    document.dispatchEvent(new CustomEvent("gepgeo:langchange", { detail: { lang: lang } }));
  }

  // Helper global para textos gerados via JS (ex: mensagens de formulário, carrinho, preview)
  window.i18nText = function (key) {
    var lang = window.__gepgeoLang || "pt";
    var dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;
    return (dict[key] || TRANSLATIONS.pt[key] || key).replace(/<[^>]+>/g, "");
  };

  document.addEventListener("DOMContentLoaded", function () {
    var lang = getSavedLang();
    if (lang !== "pt" && lang !== "en") lang = "pt";
    applyLanguage(lang);

    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.addEventListener("click", function () {
        var lang = btn.dataset.lang;
        saveLang(lang);
        applyLanguage(lang);
      });
    });

    var observer = new MutationObserver(function () {
      applyLanguage(window.__gepgeoLang || "pt");
    });
    observer.observe(document.body, { childList: true });
    setTimeout(function () { observer.disconnect(); }, 3000);
  });
